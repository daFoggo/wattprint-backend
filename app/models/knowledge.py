import uuid
from datetime import date

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Computed,
    Date,
    ForeignKey,
    Identity,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from ..database import Base

_UUID_DEFAULT = text("gen_random_uuid()")

EMBEDDING_DIM = 1024


class Document(Base):
    __tablename__ = "document"
    __table_args__ = (
        CheckConstraint(
            "doc_type IN ('standard','guide','tariff','expert_rule','other')", name="doc_type"
        ),
        {"schema": "knowledge"},
    )

    id: Mapped[uuid.UUID] = mapped_column(
        primary_key=True, default=uuid.uuid4, server_default=_UUID_DEFAULT
    )
    title: Mapped[str] = mapped_column(Text)
    doc_type: Mapped[str] = mapped_column(String(16))
    lang: Mapped[str] = mapped_column(Text, default="vi", server_default="vi")
    source_url: Mapped[str | None] = mapped_column(Text)
    version: Mapped[str | None] = mapped_column(Text)
    license_note: Mapped[str | None] = mapped_column(Text)
    published_at: Mapped[date | None] = mapped_column(Date)


class Chunk(Base):
    """Text chunk with an embedding. `tsv` is generated by the database and read-only."""

    __tablename__ = "chunk"
    __table_args__ = (
        UniqueConstraint("document_id", "ord"),
        Index("ix_chunk_tsv", "tsv", postgresql_using="gin"),
        Index(
            "ix_chunk_embedding",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
            postgresql_with={"m": 16, "ef_construction": 64},
        ),
        {"schema": "knowledge"},
    )

    id: Mapped[int] = mapped_column(BigInteger, Identity(always=False), primary_key=True)
    document_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("knowledge.document.id", ondelete="CASCADE")
    )
    ord: Mapped[int] = mapped_column(Integer)
    body: Mapped[str] = mapped_column(Text)
    tsv = mapped_column(
        TSVECTOR,
        Computed("to_tsvector('simple', knowledge.immutable_unaccent(body))", persisted=True),
    )
    embedding = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    embedding_model: Mapped[str] = mapped_column(Text)
    token_count: Mapped[int | None] = mapped_column(Integer)
