"""Score what the NILM worker wrote against REFIT's own appliance plugs, end to end.

For each demo home, over its last `--days` of estimates: the ground truth is the CSV's appliance
channel, preprocessed as for training (Issues dropped, under 5 W -> 0, over 10 kW -> 10 kW), moved
onto database time with the home's shift (scripts/refit.py) and averaged per 15 s bin. Metrics as in
train.ipynb §6: energy matched step by step (F1), kWh error. It also says whether those days were
part of the model's training data (in-sample) or after it (held out): only held-out numbers say how
the model generalises. Writes docs/nilm-eval.md.

    uv run python -m scripts.eval_nilm [--days 30]
"""

import argparse
import asyncio
import json
from datetime import UTC, datetime, timedelta
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
STEP = pd.Timedelta(seconds=15)
# Device type -> CSV channel per house (CLEAN_READ_ME_081116.txt), as in train_house.py.
CHANNELS = {
    2: {
        "fridge_freezer": "Appliance1",
        "washing_machine": "Appliance2",
        "dishwasher": "Appliance3",
        "microwave": "Appliance5",
        "toaster": "Appliance6",
        "kettle": "Appliance8",
    },
    3: {
        "fridge_freezer": "Appliance2",
        "washing_machine": "Appliance6",
        "dishwasher": "Appliance5",
        "microwave": "Appliance8",
        "toaster": "Appliance1",
        "kettle": "Appliance9",
    },
    5: {
        "fridge_freezer": "Appliance1",
        "washing_machine": "Appliance3",
        "dishwasher": "Appliance4",
        "microwave": "Appliance7",
        "toaster": "Appliance9",
        "kettle": "Appliance8",
    },
    6: {
        "freezer": "Appliance1",
        "washing_machine": "Appliance2",
        "dishwasher": "Appliance3",
        "microwave": "Appliance6",
        "toaster": "Appliance8",
        "kettle": "Appliance7",
    },
}


def truth(house: int, shift_days: int, lo: datetime, hi: datetime) -> pd.DataFrame:
    """Appliance W per 15 s bin on database time, preprocessed as the training data."""
    from scripts import refit

    cols = list(CHANNELS[house].values())
    df = pd.read_csv(
        ROOT / "dataset" / f"CLEAN_House{house}.csv", usecols=["Unix", *cols, "Issues"]
    )
    df = df.loc[df["Issues"] != 1]
    v = df[cols]
    df[cols] = v.clip(upper=10_000).mask(v.notna() & (v < 5), 0)
    wall = pd.to_datetime(df["Unix"], unit="s", utc=True).dt.tz_convert(refit.SOURCE_TZ)
    ts = refit.db_time(wall.dt.tz_localize(None).to_numpy(), shift_days)
    frame = pd.DataFrame(df[cols].to_numpy(), index=ts, columns=cols).sort_index()
    frame = frame.loc[(frame.index >= lo) & (frame.index < hi)]
    return frame.resample(STEP, origin="epoch").mean()


def scores(pred: pd.Series, true: pd.Series) -> dict:
    both = pred.notna() & true.notna()
    p, t = pred[both].to_numpy(), true[both].to_numpy()
    k = STEP.total_seconds() / 3.6e6
    match = np.minimum(p, t).sum()
    return {
        "true kWh": t.sum() * k,
        "pred kWh": p.sum() * k,
        "kWh err %": 100 * (p.sum() / t.sum() - 1) if t.sum() else float("nan"),
        "energy F1": 2 * match / max(p.sum() + t.sum(), 1e-9),
        "bins": int(both.sum()),
    }


async def main(days: int) -> None:
    from sqlalchemy import text

    from app.database import SessionLocal
    from scripts import refit
    from scripts.seed_demo_homes import load_env  # noqa: F401  (env is loaded before this import)

    now = datetime.now(UTC)
    lo = now - timedelta(days=days)
    lines = [
        "# NILM: pipeline output against REFIT's appliance plugs",
        "",
        f"Generated by `scripts/eval_nilm.py` on {now:%Y-%m-%d %H:%M} UTC over the last "
        f"{days} days of "
        "estimates in the database. Ground truth: the house's own plug channels, preprocessed as "
        "the training data. Energy F1 matches energy step by step (15 s), so energy at the wrong "
        "time does not count.",
        "",
    ]
    async with SessionLocal() as s:
        homes = (
            await s.execute(
                text(
                    "SELECT h.id, h.name, w.source, w.shift_days, m.artifact, m.version "
                    "FROM etl.tb_watermark w "
                    "JOIN public.tb_meter mt ON mt.serial = 'REFIT-H' || "
                    "substring(w.source FROM 'House([0-9]+)') "
                    "JOIN public.tb_home h ON h.id = mt.home_id "
                    "JOIN LATERAL (SELECT artifact, version FROM public.tb_nilm_model WHERE active "
                    "AND (home_id = h.id OR home_id IS NULL) "
                    "ORDER BY home_id NULLS LAST LIMIT 1) m "
                    "ON true WHERE w.segment = 'demo' ORDER BY h.name"
                )
            )
        ).all()
        for home in homes:
            house = refit.house_of(home.source)
            meta = json.loads(
                (
                    ROOT / "dataset" / "models" / "nilm" / Path(home.artifact).with_suffix(".json")
                ).read_text()
            ).get("meta", {})
            rows = (
                await s.execute(
                    text(
                        "SELECT e.ts, d.device_type_code AS type, e.value "
                        "FROM public.tb_device_estimate e "
                        "JOIN public.tb_series x USING (series_id) "
                        "JOIN public.tb_device d ON d.id = x.device_id "
                        "WHERE x.home_id = :h AND e.ts >= :lo AND e.ts < :hi"
                    ),
                    {"h": home.id, "lo": lo, "hi": now},
                )
            ).all()
            est = pd.DataFrame(rows, columns=["ts", "type", "value"]).pivot(
                index="ts", columns="type", values="value"
            )
            est.index = pd.DatetimeIndex(est.index).tz_convert(UTC)
            gt = truth(house, home.shift_days, lo, now)
            wall_lo = pd.Timestamp(lo).tz_convert(refit.HOME_TZ).tz_localize(None) - timedelta(
                days=home.shift_days
            )
            trained_on = meta.get("house", 2) == house
            until = pd.Timestamp(meta.get("trained_until", "1970-01-01"))
            held_out = trained_on and wall_lo > until
            where = (
                "held out (after the model's training data)"
                if held_out
                else (
                    "in-sample (inside the model's training period)"
                    if trained_on
                    else f"another house (model trained on House {meta.get('house', 2)})"
                )
            )
            table = {
                t: scores(est[t], gt[c]) for t, c in CHANNELS[house].items() if t in est and c in gt
            }
            df = pd.DataFrame(table).T
            macro = df["energy F1"].mean()
            total = 100 * (df["pred kWh"].sum() / df["true kWh"].sum() - 1)
            lines += [
                f"## {home.name}",
                "",
                f"Model `{home.artifact}` ({home.version}). Days scored: REFIT wall clock from "
                f"{wall_lo:%Y-%m-%d}: **{where}**. Macro energy F1 **{macro:.3f}**, "
                f"total kWh error of the six appliances **{total:+.1f} %**.",
            ]
            if "test_summary" in meta:
                ts = meta["test_summary"]
                lines.append(
                    "The model's own held-out test (from training): "
                    f"energy F1 {ts['energy F1']:.3f}, "
                    f"total kWh error {ts['total kWh err %']:+.1f} %."
                )
            lines += [
                "",
                "| Device | True kWh | Estimated kWh | kWh error | Energy F1 |",
                "|---|---:|---:|---:|---:|",
            ]
            for t, r in df.iterrows():
                lines.append(
                    f"| {t} | {r['true kWh']:.1f} | {r['pred kWh']:.1f} | "
                    f"{r['kWh err %']:+.0f} % | {r['energy F1']:.3f} |"
                )
            lines.append("")
            print("\n".join(lines[-(len(df) + 6) :]), flush=True)
    out = ROOT / "docs" / "nilm-eval.md"
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    from scripts.seed_demo_homes import load_env

    load_env()
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=30)
    asyncio.run(main(ap.parse_args().days))
